// «Остров загадок»: a logic game for children 7–9. Five islands, six puzzles on each.

export type ChoicePuzzle = {
  id: string;
  kind: "choice";
  q: string;
  /** A big row of pictures (the pattern, the things to compare). */
  show?: string;
  options: string[];
  answer: number;
  explain: string;
};

/** "Who lives where": put every character into exactly one place so that all the clues are true. */
export type GridPuzzle = {
  id: string;
  kind: "grid";
  q: string;
  who: string[];
  where: string[];
  clues: string[];
  /** For every character — the index of their place. */
  answer: number[];
  explain: string;
};

export type Puzzle = ChoicePuzzle | GridPuzzle;
export type Island = { id: number; name: string; emoji: string; about: string; color: string; puzzles: Puzzle[] };

