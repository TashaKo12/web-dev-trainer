// Станция «Маяк» — the second station of «Тайна станции». Pixel writes commands as words:
// he lights the lamps of a space lighthouse and carries batteries to its sockets.

export type BeaconLevel = {
  id: string;
  title: string;
  /** . floor, # wall, o lamp, b battery, x socket. */
  map: string[];
  start: { x: number; y: number; dir: Dir };
  intro: string;
  hint: string;
  /** A program that solves the level: checked by a script; its length is the goal for the second star. */
  solution: string;
  /** Words the program must use: the level is about them. */
  require?: ("повтори" | "команда")[];
  boss?: boolean;
};

export type Deck = {
  id: number;
  name: string;
  emoji: string;
  /** The letter that lights up on the lighthouse when the deck is repaired. */
  letter: string;
  about: string;
  /** The new words of the deck: the cheat sheet in every level. */
  words: { word: string; about: string }[];
  theory: GameTheory;
  levels: BeaconLevel[];
};

