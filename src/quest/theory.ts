const CMD: Record<string, string> = { F: "вперёд()", L: "налево()", R: "направо()", W: "полить()", A: "моя_команда()" };

function lines(nodes: Node[], pad: string): string[] {
  if (!nodes.length) return [`${pad}pass  # пусто`];
  return nodes.flatMap((n) => {
    if (n.k === "cmd") return [pad + CMD[n.c]];
    if (n.k === "loop") return [`${pad}for i in range(${n.n}):`, ...lines(n.body, pad + "    ")];
    if (n.k === "while") return [`${pad}while not на_выходе():`, ...lines(n.body, pad + "    ")];
    const out = [`${pad}if стена_впереди():`, ...lines(n.then, pad + "    ")];
    if (n.else.length) out.push(`${pad}else:`, ...lines(n.else, pad + "    "));
    return out;
  });
}

/** The child's block program as Python code. */
export function toPython(p: Program): string {
  const fn = p.fn.length ? ["def моя_команда():", ...lines(p.fn, "    "), ""] : [];
  return [...fn, ...lines(p.main, "")].join("\n");
}
