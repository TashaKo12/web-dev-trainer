const CMD: Record<string, string> = { F: "вперёд", L: "налево", R: "направо", W: "полить", A: "⭐" };
const times = (n: number) => (n % 10 >= 2 && n % 10 <= 4 && (n < 12 || n > 14) ? "раза" : "раз");

function lines(nodes: Node[], pad: string): string[] {
  if (!nodes.length) return [`${pad}(пусто)`];
  return nodes.flatMap((n) => {
    if (n.k === "cmd") return [pad + CMD[n.c]];
    if (n.k === "loop") return [`${pad}повтори ${n.n} ${times(n.n)}:`, ...lines(n.body, pad + "    ")];
    if (n.k === "while") return [`${pad}пока не выход:`, ...lines(n.body, pad + "    ")];
    const out = [`${pad}если стена впереди:`, ...lines(n.then, pad + "    ")];
    if (n.else.length) out.push(`${pad}иначе:`, ...lines(n.else, pad + "    "));
    return out;
  });
}

/** The child's block program written out as text, with indents like in a real program. */
export function programText(p: Program): string {
  const fn = p.fn.length ? ["моя команда ⭐:", ...lines(p.fn, "    "), ""] : [];
  return [...fn, ...lines(p.main, "")].join("\n");
}
